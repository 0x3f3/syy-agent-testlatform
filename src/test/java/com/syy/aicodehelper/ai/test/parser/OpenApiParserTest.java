package com.syy.aicodehelper.ai.test.parser;

import com.fasterxml.jackson.databind.ObjectMapper;
import com.syy.aicodehelper.ai.test.entity.ApiDefinition;
import org.junit.jupiter.api.Test;
import java.io.ByteArrayInputStream;
import java.nio.charset.StandardCharsets;
import java.util.List;
import static org.junit.jupiter.api.Assertions.*;

class OpenApiParserTest {
 @Test void parsesOpenApiPathsAndMethods() throws Exception {
  String spec = """
   {
    "openapi":"3.0.0",
    "info":{"title":"Demo","version":"1.0"},
    "servers":[{"url":"http://localhost:8081"}],
    "paths":{
     "/users":{"get":{"summary":"List users"},"post":{"summary":"Create user"},"parameters":[{"name":"X-Trace-Id","in":"header"}]},
     "/health":{"get":{"summary":"Health check"}}
    }
   }
   """;
  ParsedOpenApi parsed = new OpenApiParser(new ObjectMapper()).parse(new ByteArrayInputStream(spec.getBytes(StandardCharsets.UTF_8)));
  List<ApiDefinition> apis = parsed.apis();
  assertEquals("Demo", parsed.title()); assertEquals("http://localhost:8081", parsed.serverUrl());
  assertEquals(3, apis.size()); assertEquals("/users", apis.get(0).getPath());
  assertEquals("GET", apis.get(0).getMethod()); assertEquals("List users", apis.get(0).getDescription());
  assertEquals("POST", apis.get(1).getMethod()); assertEquals("/health", apis.get(2).getPath());
  assertNull(apis.get(0).getId(), "ID is generated by MySQL when persisted");
 }
}
